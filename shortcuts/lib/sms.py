# -*- coding: utf-8 -*-
"""短信验证码：抽取用的正则常量 + 电脑侧预演函数。

真机上跑的是快捷指令的「匹配文本」动作，模式串由
`shortcuts/短信同步/build.py` 从这里取；`extract()` 只是让同一套模式
能在电脑上跑测试（`tests/test_sms_code.py`），不上手机。

两条模式，先 A 后 B
-------------------
A  关键词在前 —— 「验证码：123456」「校验码为 8888」「code is 654321」
   关键词与数字之间的间隔只允许「非字母数字字符」或单独的 `is`：
   中文写法里的「为 / 是 / ：」都算非字母数字，英文的 "is" 单独放行。
   间隔上限 12 个字符，够跨过「请勿泄露给任何人，」这种插入语；
   跨度里**不允许出现数字**，所以「验证码有效期5分钟，11月23日」这类
   句子里的 5 / 11 / 23 不会被当成候选。

B  验证码在前 —— 「123456 是您的登录验证码」
   国内短信里少数这样写，只在 A 没命中时才跑。下限收到 5 位：
   4 位数在前、后面又跟关键词的写法极少见，而「支付1234元后可获取验证码」
   这种句子正好会把 1234 误当成码。

共同约束
--------
* 4–8 位纯数字。带字母的码（AB12CD）与实际短信里的占比太低，而放宽到字母后
  「验证码获取失败 Please retry」这种句子会命中 Please，代价不划算。
* 后面紧跟 0–9 位数字的不算（`验证码123456789` 是 9 位订单号，不截前 6 位），
  紧跟「年 / 月 / 日 / 时 / 分 / 秒」的也不算（`有效期至2026年` 里的 2026）。
* B 还要求左边不是字母数字：避免从一长串数字中间截一段。

已知不匹配
----------
* 纯英文、且关键词与数字之间夹着别的单词：「Your verification code is」能中
  （is 放行），「Your verification code has been sent: 123456」不中。
* 全角数字（１２３４５６）不匹配，真实短信里几乎见不到。
"""

import re

# 中英文关键词。长的写在前面：「验证代码 / 验证口令」要先于「代码 / 口令」，
# 否则正则回溯时会先撞上短的那个，虽然结果一样，但读起来容易误判。
KEYWORDS = (
    '验证码|校验码|动态码|验证代码|确认码|安全码|短信密码|动态密码|'
    '验证口令|口令|代码|[Cc][Oo][Dd][Ee]|OTP|PIN'
)

_KEY = '(?:%s)' % KEYWORDS

# A：关键词在前。`[^0-9A-Za-z]` 与 `[Ii][Ss]` 二选一，重复 0–12 次。
PATTERN_A = _KEY + r'(?:[^0-9A-Za-z]|[Ii][Ss]){0,12}([0-9]{4,8})(?![0-9年月日时分秒])'

# B：数字在前，关键词在后。左边不许紧贴字母数字，右边不许再跟数字。
PATTERN_B = r'(?<![0-9A-Za-z])([0-9]{5,8})(?![0-9])[^0-9A-Za-z]{0,8}' + _KEY

PATTERNS = (PATTERN_A, PATTERN_B)


def extract(text):
    """按 A→B 的顺序抽验证码；抽不到返回 None。仅电脑侧使用。"""
    if not text:
        return None
    for pattern in PATTERNS:
        m = re.search(pattern, text)
        if m and m.group(1):
            return m.group(1)
    return None
