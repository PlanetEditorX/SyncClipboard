# -*- coding: utf-8 -*-
"""短信验证码抽取（shortcuts/lib/sms.py）。

这一套模式真正跑在手机上（快捷指令的「匹配文本」动作），电脑上这个是同一份
字符串 —— 所以这里过不了，手机上也过不了。句式取自真实收到的验证码短信：
国内常见的是「关键词在前」（验证码：123456），少数是「数字在前」（123456 是
您的验证码），两条模式各管一种。

反面用例（不该抽到东西）比正面用例重要：误抽一个订单号/金额/日期，用户会把
它当成验证码发出去，比「没抽到」糟得多。
"""

import os
import sys
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))), 'shortcuts'))

from lib.sms import extract  # noqa: E402


class ExtractCodeTest(unittest.TestCase):
    # --- 关键词在前：模式 A ---
    CASES = [
        # 银行/支付类：正文里还有金额，金额不能盖掉真验证码
        ('【中国银行】您正在支付1,234.00元，验证码：123456，请勿告诉他人。',
         '123456'),
        ('您的验证码为 654321，5分钟内有效。', '654321'),
        ('【淘宝】校验码：8888，10分钟内有效。', '8888'),
        ('动态码 445566，请勿转发', '445566'),
        ('验证码：12345（5位）', '12345'),
        ('验证码为8888，如非本人操作请忽略', '8888'),
        # 关键词和数字之间夹着插入语
        ('验证码：请勿泄露给任何人，123456', '123456'),
        # 换行后才是数字
        ('您正在登录，验证码如下：\n772431', '772431'),
        # 英文连词 is 放行
        ('【Apple】Apple ID 代码：123456，请勿与任何人共享。', '123456'),
        ('Your code: 123456', '123456'),
        # 8 位码
        ('【某平台】您的验证码为87654321', '87654321'),

        # --- 数字在前：模式 B ---
        ('123456 是您的登录验证码，请勿泄露。', '123456'),
        ('678901是您本次操作的校验码', '678901'),
    ]

    # --- 不该抽到东西 ---
    NEGATIVE = [
        # 年份+日期，不是验证码
        '验证码有效期至2026年11月23日，请及时使用',
        # 消费提醒，根本没有验证码
        '【某银行】您的账户于11月23日消费100元',
        # 只说「已发送至」，号码是脱敏手机号
        '验证码已发送至138****1234，请查收',
        # 9 位是订单号，不许截前 6 位
        '验证码123456789',
        # 订单号里不该截出一段
        '订单号20241123000123已发货',
        # 金额在前、关键词在后：4 位数不算（模式 B 下限 5 位）
        '支付1234元后可获取验证码',
        # 空 / None
        '',
        None,
        # 普通聊天
        '晚上一起吃饭吗',
    ]

    def test_positive_cases(self):
        for text, want in self.CASES:
            with self.subTest(text=text):
                self.assertEqual(extract(text), want)

    def test_negative_cases(self):
        for text in self.NEGATIVE:
            with self.subTest(text=text):
                self.assertIsNone(extract(text))


if __name__ == '__main__':
    unittest.main()
